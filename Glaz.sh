# Tool check
function tool_check() {
    clear
    ascii_art
    echo -e "${yellow}Loading...${nc}"
    
    tools="nmap xmlstarlet searchsploit medusa hydra ipcalc tree xsltproc zip figlet"
    
    for tool in $tools; do
