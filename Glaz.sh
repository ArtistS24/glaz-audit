    case "$choice" in
        1) search_path="/home/" ;;
        2) search_path="/" ;;
        3) return ;;
        *) echo -e "${neon_red}✖ Invalid choice.${nc}"; sleep 1; return ;;
    esac

    clear
    ascii_art
    echo -e "${neon_pink}Searching for Glaz markers in ${search_path}...${nc}"
    echo -e "${neon_yellow}[*] This may take a moment.${nc}"

    # Find the scan files 
    local initial_scan_files=()
    while IFS= read -r line; do
        initial_scan_files+=("$line")
    done < <(find "$search_path" -type f -name ".DATA" -exec grep -l "VGhpcyBpcyBHbGF6IE1hcms=" {} + 2>/dev/null)

    if [ ${#initial_scan_files[@]} -eq 0 ]; then
        echo
        echo -e "${neon_red}✖ No previous scan markers found in ${search_path}.${nc}"
        echo
        read -p "Press Enter to return..."
        return
    fi

    local sortable_list=()
    for path in "${initial_scan_files[@]}"; do
        local date_key=$(echo "$path" | awk -F'/' '{print $(NF-2)}')
        sortable_list+=("${date_key}|${path}")
    done

    local scan_files=() 
    while IFS='|' read -r date_key original_path; do
        scan_files+=("$original_path")
    done < <(printf "%s\n" "${sortable_list[@]}" | sort -r)


    # Display the scan files
    while true; do
        clear
        ascii_art
        echo -e "${neon_green}✔ Scans Found: ${neon_cyan}${#scan_files[@]}${nc}\n"
        echo -e "${neon_purple}#   IP Address/CIDR      -      Date       Time${nc}"
