# View brute force logs function
function view_brute_force_logs() {
    local brute_dir="$1"

    if [ ! -d "$brute_dir" ]; then
        echo -e "${neon_red}✖ Brute-force directory not found.${nc}"
        sleep 2
        return
    fi

    while true; do
        clear
        ascii_art
        echo -e "${neon_purple}╭──────────────────────────────────────────────────────────────╮${nc}"
        echo -e "${neon_blue}│         ⧉ ${neon_purple}ＢＲＵＴＥ - ＦＯＲＣＥ   ＬＯＧＳ ${neon_blue}⧉         │${nc}"
        echo -e "${neon_purple}╰──────────────────────────────────────────────────────────────╯${nc}"
        echo

        #  Find which services have logs
        local services=()
        while IFS= read -r dir; do
            services+=("$(basename "$dir")")
        done < <(find "$brute_dir" -mindepth 1 -maxdepth 1 -type d)

        if [ ${#services[@]} -eq 0 ]; then
            echo -e "${neon_yellow}[!] No brute-force logs found for any service.${nc}"
            sleep 2
            return
        fi
       
        echo -e "${neon_cyan}Which service logs would you like to review?${nc}"
        local i=1
        for service in "${services[@]}"; do
            echo -e "${magenta} [${i}] ${service^}${nc}" 
            ((i++))
        done
        echo -e "${neon_red} [B] Back to Previous Menu${nc}"
        echo
        read -p "Choose an option: " service_choice

        if [[ "$service_choice" =~ ^[0-9]+$ && "$service_choice" -ge 1 && "$service_choice" -le "${#services[@]}" ]]; then
            local selected_service=${services[service_choice-1]}
            local service_log_dir="${brute_dir}/${selected_service}"
            # Log type selection
            while true; do
                clear
                ascii_art
                echo -e "${neon_pink}Selected Service: ${neon_green}${selected_service^}${nc}\n"
                echo -e "${magenta}[1] View Full Brute-force Logs${nc}"
                echo -e "${magenta}[2] View Successful Logins Only${nc}"
                echo -e "${neon_red}[B] Back to Service Selection${nc}"
                echo
                read -p "Choose log type: " log_type_choice

                local full_log
                local success_log

                
                    # Define log file paths
                    full_log="${service_log_dir}/${selected_service}_brute.logs"
                    success_log="${service_log_dir}/${selected_service}_successful.log"
                


                case "$log_type_choice" in
                    1)
                        if [ -f "$full_log" ]; then
                            less -R "$full_log"
                        else
                            echo -e "${neon_red}✖ Full log file not found!${nc}"; sleep 2
                        fi
                        ;;
                    2)
                        if [ -f "$success_log" ]; then
                            less -R "$success_log"
                        else
                            echo -e "${neon_red}✖ Successful log file not found!${nc}"; sleep 2
                        fi
                        ;;
                    [Bb])
                        break ;;
                    *)
                        echo -e "${neon_red}✖ Invalid choice.${nc}"; sleep 1 ;;
                esac
            done
        # Back to main menu
        elif [[ "$service_choice" =~ ^[Bb]$ ]]; then
            break
        else
            echo -e "${neon_red}✖ Invalid choice. Please try again.${nc}"
            sleep 1
        fi
    done
}

