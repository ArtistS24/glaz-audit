# Get from the user a network to scan. 
function ip_input() {

    ascii_art

    echo -e "${neon_pink}╭──────────────────────────────────────────────────────────────╮${nc}"
    echo -e "${neon_blue}│    ⧉ ${neon_purple}ＮＥＴＷＯＲＫ　ＳＣＡＮ　ＴＡＲＧＥＴ　ＳＥＴＵＰ ${neon_blue}⧉    │${nc}"
    echo -e "${neon_pink}╰──────────────────────────────────────────────────────────────╯${nc}"
    echo

    echo -e "${neon_green}Welcome to глаз-Glaz.${nc}"
    echo
     # Get IP
    while true; do
        echo -ne "${neon_cyan}➤ Enter your IP to scan${nc} ${white_bold}(type ${neon_blue}eth0${white_bold} to auto-detect): ${nc}"
        read -r input_ip
        if [[ "$input_ip" == "eth0" ]]; then
            ip=$(ip route | grep -i eth0 | awk -F "src" '{print $2}' | awk '{print $1}' | head -n1)
            if [[ -z "$ip" ]]; then
                echo -e "${neon_red}✖ Could not detect IP for eth0. Please enter it manually.${nc}"
                continue
            fi
            echo -e "${neon_green}✔ IP detected: ${neon_pink}${ip}${nc}"
            break
        elif [[ "$input_ip" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]]; then
            ip="$input_ip"
            echo -e "${neon_green}✔ You entered: ${neon_pink}${ip}${nc}"
            break
        else
            echo -e "${neon_red}✖ Invalid IP address. Try again.${nc}"
            sleep 1
        fi
    done
       # Get Cidr
    echo
    while true; do
        echo -ne "${neon_cyan}➤ Enter CIDR (e.g., /24) or leave blank to auto-detect: ${nc}"
        read -r input_cidr
        if [[ -z "$input_cidr" ]]; then
            detected_cidr=$(ip route | awk 'NR==2 {print $1}' | awk -F "/" '{print $2}' 2>/dev/null)
            if [[ -n "$detected_cidr" ]]; then
                cidr="$detected_cidr"
                echo -e "${neon_green}✔ Detected CIDR: ${neon_pink}/${cidr}${nc}"
                break
            else
                echo -e "${neon_red}✖ CIDR detection failed. Please enter manually.${nc}"
                continue
            fi
        elif [[ "$input_cidr" =~ ^/[0-9]+$ ]]; then
            cidr_num="${input_cidr#/}"
            
            if (( cidr_num >= 0 && cidr_num <= 32 )); then
                cidr="$cidr_num"
                echo -e "${neon_green}✔ Your CIDR: ${neon_pink}/${cidr}${nc}"
                break
            else
                echo -e "${neon_red}✖ Invalid CIDR value. Must be between /0 and /32.${nc}"
                sleep 1
            fi
        else
            echo -e "${neon_red}✖ Invalid CIDR value. Must be between /0 and /32.${nc}"
            sleep 1
        fi
    done
      # Get output directory
    echo
    while true; do
        echo -ne "${neon_cyan}➤ Name the output directory ${white_bold}(default: ${neon_blue}Glaz${white_bold}): ${nc}"
        read -r input_output_dir
        if [[ -z "$input_output_dir" ]]; then
            output_dir="Glaz"
            echo -e "${neon_green}✔ Using default directory: ${neon_pink}${output_dir}${nc}"
            break
        else
            output_dir="$input_output_dir"
            echo -e "${neon_green}✔ Output directory set: ${neon_pink}${output_dir}${nc}"
            break
        fi
    done

    mkdir -p "$output_dir"
    echo -e "${neon_cyan}   Directory ensured: ${neon_pink}${output_dir}${nc}"
    echo
}
