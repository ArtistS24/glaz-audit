            echo "$path" | awk -F'/' -v offset="$i" '{
                gsub(/_/, "/", $(NF-3));
                split($(NF-2), dt, "_");
                gsub(/-/, ":", dt[2]);
                printf "[%d] %-20s - %s  %s\n", (NR-1)+offset+1, $(NF-3), dt[1], dt[2]
            }'
        done

        echo -e "\n${neon_red} [B] Back to Main Menu${nc}"
        echo
        read -p "Enter a number to inspect a scan, or [B] to go back: " scan_choice

        if [[ "$scan_choice" =~ ^[Bb]$ ]]; then
            break
        fi

        if [[ "$scan_choice" =~ ^[0-9]+$ && "$scan_choice" -ge 1 && "$scan_choice" -le "${#scan_files[@]}" ]]; then
            local selected_path="${scan_files[scan_choice-1]}"
            local scan_dir
            scan_dir=$(dirname "$selected_path") 

            while true; do
                clear
                ascii_art
                echo -e "${neon_cyan}Inspecting Scan: ${neon_pink}${scan_dir}${nc}\n"
                echo -e "${neon_yellow}"
                tree -C -L 3 "$scan_dir" # Tree command to display directory structure
                echo -e "${nc}"
                echo -e "${neon_purple}╭─────────────────── ACTIONS ────────────────────╮${nc}"
                echo -e "${magenta}│ [1] View Nmap Log (scan.log)                   │${nc}"
                echo -e "${magenta}│ [2] Open HTML Report in Browser                │${nc}"
                echo -e "${magenta}│ [3] View Brute-Force Logs                      │${nc}"
                echo -e "${magenta}│ [4] View Vulnerability Report                  │${nc}"
                echo -e "${neon_red}│ [B] Back to Scan Selection                     │${nc}"
                echo -e "${neon_purple}╰────────────────────────────────────────────────╯${nc}"
                echo
                read -p "Choose an action: " action_choice
